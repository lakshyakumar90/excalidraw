/** Deterministic 32-bit PRNG. Its output is independent of JS object order. */
export function mulberry32(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4_294_967_296;
  };
}

/** Derive stable independent streams so fills and outline passes cannot perturb one another. */
export function deriveSeed(seed: number | undefined, stream: number): number {
  let value = (seed ?? 0x51f15e) >>> 0;
  value ^= stream >>> 0;
  value = Math.imul(value ^ (value >>> 16), 0x7feb352d);
  value = Math.imul(value ^ (value >>> 15), 0x846ca68b);
  return (value ^ (value >>> 16)) >>> 0;
}
